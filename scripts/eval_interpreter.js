/* Evaluate the payment-message interpreter on tests/eval/hinglish_messages.json.
 *
 *   node scripts/eval_interpreter.js            rule-based fallback only (always runs, no network)
 *   OPENAI_API_KEY=... node scripts/eval_interpreter.js   also runs the live model through api/parse-promise.js
 *
 * Writes tests/eval/RESULTS.md with the observed numbers. Nothing is estimated or filled in.
 */
const fs = require('fs'); const path = require('path');
const R = require('../lib/promise-rules.js');
const handler = require('../api/parse-promise.js');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, '../tests/eval/hinglish_messages.json'), 'utf8'));

function score(rows) {
  const n = rows.length; const ok = (f) => rows.filter(f).length;
  const amt = (r) => (r.got.promisedAmountNow ?? null) === r.exp.now && (r.got.promisedAmountLater ?? null) === r.exp.later;
  const date = (r) => (r.got.firstPaymentDate ?? null) === r.exp.firstDate && (r.got.promisedDate ?? null) === r.exp.laterDate;
  const withAmt = rows.filter((r) => r.exp.now != null || r.exp.later != null), withDate = rows.filter((r) => r.exp.firstDate || r.exp.laterDate);
  return {
    n, intent: ok((r) => r.got.intent === r.exp.intent) / n,
    amountAll: ok(amt) / n, amountWhereStated: withAmt.filter(amt).length / withAmt.length,
    dateAll: ok(date) / n, dateWhereStated: withDate.filter(date).length / withDate.length,
    clarify: ok((r) => r.got.needsClarification === r.exp.clarify) / n,
    noFalseConfirm: ok((r) => !(r.canConfirm && r.exp.clarify)) / n,
    misses: rows.filter((r) => !(r.got.intent === r.exp.intent && amt(r) && date(r) && r.got.needsClarification === r.exp.clarify)).map((r) => r.exp.id),
  };
}
const pct = (x) => (x * 100).toFixed(1) + '%';

async function live() {
  if (!process.env.OPENAI_API_KEY && !process.env.ANTHROPIC_API_KEY) return null;
  const rows = [];
  for (const it of data.items) {
    const res = { statusCode: 0, headers: {}, body: null, setHeader() {}, end(b) { this.body = JSON.parse(b); } };
    handler._resetRateLimit();
    await handler({ method: 'POST', headers: {}, body: { message: it.message, outstanding: it.outstanding, invoiceId: 'INV-EVAL', messageDate: data.messageDate } }, res);
    if (!res.body.ok) { rows.push({ exp: it, got: { intent: 'error:' + res.body.code }, canConfirm: false }); continue; }
    rows.push({ exp: it, got: res.body.interpretation, canConfirm: res.body.canConfirm, model: res.body.model });
  }
  return rows;
}

(async () => {
  const rule = data.items.map((it) => { const c = { message: it.message, outstanding: it.outstanding, messageDate: data.messageDate }; const v = R.validateInterpretation(R.demoParse(it.message, c), c); return { exp: it, got: v.interpretation, canConfirm: v.canConfirm }; });
  const rs = score(rule);
  const lv = await live(); const ls = lv ? score(lv) : null;
  const table = (s) => `| Intent accuracy | ${pct(s.intent)} |\n| Amounts exact (all ${s.n}) | ${pct(s.amountAll)} |\n| Amounts exact (where stated) | ${pct(s.amountWhereStated)} |\n| Dates exact (all ${s.n}) | ${pct(s.dateAll)} |\n| Dates exact (where stated) | ${pct(s.dateWhereStated)} |\n| Clarification / abstention correct | ${pct(s.clarify)} |\n| Never confirmable when clarification was needed | ${pct(s.noFalseConfirm)} |\n| Items with any mismatch | ${s.misses.length ? s.misses.join(', ') : 'none'} |`;
  const md = `# Interpreter evaluation\n\nDataset: \`tests/eval/hinglish_messages.json\` · ${data.items.length} hand-labelled Hinglish messages · message date ${data.messageDate} (Asia/Kolkata).\nGenerated by \`node scripts/eval_interpreter.js\` on ${new Date().toISOString().slice(0, 10)}.\n\n## Rule-based fallback (not AI)\n\nThe deterministic parser used only when live AI is unavailable. It was written alongside this dataset, so these numbers show the fallback is safe to demo; they are **not** a measure of AI performance.\n\n| Metric | Result |\n|---|---|\n${table(rs)}\n\n## Live model\n\n${ls ? `Model: ${lv.find((r) => r.model)?.model || 'unknown'} via api/parse-promise.js (with the same deterministic checks).\n\n| Metric | Result |\n|---|---|\n${table(ls)}` : '**Not run.** No `OPENAI_API_KEY` (or `ANTHROPIC_API_KEY`) was configured when this report was generated, so no live model results are reported. Set the key and re-run `npm run eval`.'}\n`;
  fs.writeFileSync(path.join(__dirname, '../tests/eval/RESULTS.md'), md);
  console.log(md);
})();
